/** true — пункт описывает только статус/учёбу/возраст/намерение работать или учиться, без навыка и ресурса. */
export function isPersonMetadataOnlyProfileText(text: string | null | undefined): boolean {
  if (!text) return false;
  if (isQuantityOnlyProfileText(text)) return true;
  const words = tokens(text);
  if (!words.length) return false;
  let marker = false;
  for (const w of words) {
    if (PERSON_METADATA.some((re) => re.test(w))) { marker = true; continue; }
    if (/^\d+(?:[.,]\d+)?$/.test(w) || NUMBER_WORDS.has(w) || DURATION.has(w)) { marker = true; continue; }
    if (FILLER.has(w) || PERSON_FILLER.has(w) || DURATION_ADJECTIVE.test(w)) continue;
    return false;
  }
  return marker;
}
