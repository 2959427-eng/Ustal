// «10-летний стаж», «33-летний»: прилагательное от «лет/месяц/год» после числа — та же длительность.
const DURATION_ADJECTIVE = /^(?:летн|месячн|годичн|годовал|недельн)[а-я]*$/u;
// «пятилетний», «двухмесячный»: число внутри слова. «многолетний» не считается длительностью.
const NUMERIC_DURATION_ADJECTIVE = /^(?:одно|двух|трех|четырех|пяти|шести|семи|восьми|девяти|десяти|одиннадцати|двенадцати|пятнадцати|двадцати|двадцатипяти|тридцати|сорока|пятидесяти|полу|полутора)(?:летн|месячн|годичн|годовал|недельн)[а-я]*$/u;

const tokens = (text: string) =>
  text.normalize("NFKC").toLowerCase().replace(/ё/g, "е").match(/[\p{L}\p{N}]+(?:[.,]\d+)?/gu) ?? [];

/** true — в тексте только возраст/стаж/длительность без названной деятельности или предмета. */
export function isQuantityOnlyProfileText(text: string | null | undefined): boolean {
  if (!text) return false;
  const words = tokens(text);
  if (!words.length) return false;
  let quantity = false;
  for (const w of words) {
    if (/^\d+(?:[.,]\d+)?$/.test(w) || NUMBER_WORDS.has(w)) { quantity = true; continue; }
    if (DURATION.has(w) || NUMERIC_DURATION_ADJECTIVE.test(w)) { quantity = true; continue; }
    if (DURATION_ADJECTIVE.test(w)) continue;
    if (FILLER.has(w)) continue;
    return false;
  }
  return quantity;
}

/** Текст пункта для показа: label, если он содержателен; иначе phrase; null — показывать нечего. */
export function profileItemDisplayText(label: string | null | undefined, phrase: string | null | undefined): string | null {
  const l = label?.trim();
  if (l && !isQuantityOnlyProfileText(l)) return l;
  const p = phrase?.trim();
  return p && !isQuantityOnlyProfileText(p) ? p : null;
}

type ItemFact = { kind: string; constraintType?: string | null; phrase: string; label?: string | null };
const positiveItem = (f: ItemFact) =>
  (f.kind === "capability" || f.kind === "resource") && (f.constraintType ?? "none") === "none";

/**
 * Положительные навыки/ресурсы, у которых и phrase, и label — только возраст/длительность, убираются; если такой только
 * подпись («33 года» при phrase «работаю сварщиком 33 года»), пункт сохраняется с label=null
 * (показ и matching идут по phrase). Остальные факты возвращаются без изменений.
 */
export function withoutQuantityOnlyProfileItems<T extends ItemFact>(facts: T[]): T[] {
  return facts.flatMap((f) => {
    if (!positiveItem(f)) return [f];
    const labelOnlyQuantity = !!f.label && isQuantityOnlyProfileText(f.label);
    const labelHasContent = !!f.label?.trim() && !labelOnlyQuantity;
    // Навык остаётся, если содержательна хотя бы phrase или label (phrase «10 лет», label «Сварщик»).
    if (isQuantityOnlyProfileText(f.phrase)) return labelHasContent ? [f] : [];
    if (labelOnlyQuantity) return [{ ...f, label: null } as T];
    return [f];
  });
}
