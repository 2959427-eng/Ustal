import { describe, expect, it } from "vitest";
import { isPersonMetadataOnlyProfileText as meta } from "./profile-quantity-only.js";

describe("isPersonMetadataOnlyProfileText (false positive 2026-10-30)", () => {
  it.each([
    "Студент", "студентка", "Я студент, хочу просто иногда подрабатывать", "Ищу подработку", "Подработка", "33 года",
    "Мне 33 года", "Готов учиться", "готова научиться новому", "Хочу подрабатывать в свободное время",
    "Учусь в университете", "Студент 2 курса", "Пенсионер", "Любая работа", "Без опыта, готов учиться",
  ])("только сведения о человеке: %s", (text) => expect(meta(text)).toBe(true));
  it.each([
    "Студент, делаю сайты", "студент-дизайнер", "Учусь на повара", "Студент медицинского вуза", "Готов помочь с переездом",
    "Программист", "верстаю лендинги", "Фотограф", "художник", "садовник", "Есть газель", "Интернет-реклама",
    "сварщик 10 лет", "Обучение детей", "Делаю сайты", "опыт", "",
  ])("есть деятельность или предмет (или пусто): %s", (text) => expect(meta(text)).toBe(false));
});
